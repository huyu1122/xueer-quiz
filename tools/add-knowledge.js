let changed = 0;
const unmapped = [];

BANK.forEach(q => {
  const tags = KNOWLEDGE_BY_ID[q.id];
  let list;
  if (tags && tags.length) {
    list = tags.slice();
  } else {
    unmapped.push(q.id);
    list = [BY_CHAPTER[q.subject + "|" + q.chapter] || q.chapter];
  }
  const before = JSON.stringify(q.knowledge || []);
  q.knowledge = list;
  if (before !== JSON.stringify(list)) changed++;
});

/* 序列化：保持可读格式 */
function serialize(bank) {
  const L = [];
  L.push("/**");
  L.push(" * 学而刷题 —— 题库数据");
  L.push(" * 题型: single(单选) | multiple(多选) | judge(判断) | fill(填空)");
  L.push(" * 答案: 选择题存选项下标数组; 判断题 0=正确 1=错误; 填空题存可接受答案字符串数组");
  L.push(" * 难度: 1=基础 2=中等 3=较难");
  L.push(" * knowledge: 知识点标签（受控词表），用于掌握度统计与针对性练习");
  L.push(" * 文本中 $...$ 与 $$...$$ 会渲染为 LaTeX 公式（KaTeX）");
  L.push(" */");
  L.push("const QUESTION_BANK = [");

  let last = null;
  bank.forEach((q, i) => {
    if (q.subject !== last) {
      L.push("");
      L.push(`  /* ================= ${q.subject} ================= */`);
      last = q.subject;
    }
    L.push("  {");
    L.push(`    id: ${JSON.stringify(q.id)},`);
    L.push(`    subject: ${JSON.stringify(q.subject)},`);
    L.push(`    chapter: ${JSON.stringify(q.chapter)},`);
    L.push(`    knowledge: ${JSON.stringify(q.knowledge)},`);
    L.push(`    type: ${JSON.stringify(q.type)},`);
    L.push(`    difficulty: ${q.difficulty},`);
    L.push(`    stem: ${JSON.stringify(q.stem)},`);
    if (q.options) L.push(`    options: ${JSON.stringify(q.options)},`);
    L.push(`    answer: ${JSON.stringify(q.answer)},`);
    L.push(`    analysis: ${JSON.stringify(q.analysis)}`);
    L.push("  }" + (i === bank.length - 1 ? "" : ","));
  });

  L.push("];");
  L.push("");
  L.push("/* 导出给全局使用（无构建工具，直接挂 window） */");
  L.push("window.QUESTION_BANK = QUESTION_BANK;");
  L.push("");
  return L.join("\n");
}

